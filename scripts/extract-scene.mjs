// Builds src/scene/engine.js from the scene's authoring file, design/style-test.html.
// The style test keeps its buttons and toggles; the site only needs the renderer.
// Run: pnpm scene
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('design/style-test.html', 'utf8');
const start = html.indexOf('(() => {\n');
const cut = html.indexOf('/* =====================================================================\n   display + the push-in');
if (start < 0 || cut < 0) throw new Error('scene markers not found in design/style-test.html');
let body = html.slice(start + '(() => {\n'.length, cut);
body = body.replace("buildWide(location.hash.includes('hall') ? 'hall' : 'room');", "buildWide('room');");
if (/location\.|document\.getElementById/.test(body)) throw new Error('engine still touches the page');

const out = `// GENERATED by scripts/extract-scene.mjs from design/style-test.html. Do not edit here.
export function createScene() {
${body}
const dk = proj(-3.1, -1.1, 13.5), dk2 = proj(3.1, -1.1, 13.5);
const ZW = RW / ((dk2[0] - dk[0]) * 1.04), CWX = (dk[0] + dk2[0]) / 2, CWY = dk[1] - 0.17 * RH / ZW;
return { natW, natD, RW, RH, W, H, ZW, CWX, CWY, frameRoom, frameDesk, setLid: v => { lid = lidT = v; } };
}
`;
writeFileSync('src/scene/engine.js', out);
console.log(`src/scene/engine.js: ${(out.length / 1024).toFixed(0)} KB`);
